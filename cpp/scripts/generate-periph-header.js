#!/usr/bin/env node
'use strict';

// Regenerates cpp/src/Periph.h, the Arduino umbrella header. The Arduino
// build system only adds the library's top-level src/ to the include path and
// discovers a library by a header directly inside src/, so sketches include
// <Periph.h> and get every Arduino-facing connection and chip driver header.
// Also satisfies arduino-lint LS001 (header in src/) and LS008 (header named
// after the library).
//
// Linux/Zephyr/ESP-IDF/Pico SDK/mock connection headers are skipped, the same
// set generate-keywords.js leaves out.
//
// Usage:
//   node cpp/scripts/generate-periph-header.js          # write cpp/src/Periph.h
//   node cpp/scripts/generate-periph-header.js --check  # exit 1 if Periph.h is stale

const fs = require('fs');
const path = require('path');

const SRC_DIR = path.join(__dirname, '..', 'src');
const HEADER_PATH = path.join(SRC_DIR, 'Periph.h');

const NON_ARDUINO_HEADER = /(Linux|Zephyr|ESPIDF|PicoSDK|Mock)\.h$/;

function listHeaders(dir) {
    const out = [];
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) out.push(...listHeaders(full));
        else if (entry.name.endsWith('.h') && !NON_ARDUINO_HEADER.test(entry.name)) out.push(full);
    }
    return out;
}

function buildHeader() {
    const rel = (p) => path.relative(SRC_DIR, p).split(path.sep).join('/');
    const connection = listHeaders(path.join(SRC_DIR, 'connection')).map(rel).sort();
    const chips = listHeaders(path.join(SRC_DIR, 'chips')).map(rel).sort();
    const lines = [
        '// Generated by cpp/scripts/generate-periph-header.js -- do not edit.',
        '//',
        '// Arduino umbrella header: #include <Periph.h> to use any Periph connection',
        '// or chip driver.',
        '#pragma once',
        '',
        '// Connections',
        ...connection.map((h) => `#include "${h}"`),
        '',
        '// Chip drivers',
        ...chips.map((h) => `#include "${h}"`),
        '',
    ];
    return lines.join('\n');
}

function main() {
    const checkOnly = process.argv.includes('--check');
    const content = buildHeader();
    const existing = fs.existsSync(HEADER_PATH) ? fs.readFileSync(HEADER_PATH, 'utf8') : null;

    if (existing === content) return;

    if (checkOnly) {
        console.error(`stale or missing: ${path.relative(process.cwd(), HEADER_PATH)}`);
        console.error('Run `node cpp/scripts/generate-periph-header.js` and commit the result.');
        process.exit(1);
    }

    fs.writeFileSync(HEADER_PATH, content);
    console.log(`wrote ${path.relative(process.cwd(), HEADER_PATH)}`);
}

main();
