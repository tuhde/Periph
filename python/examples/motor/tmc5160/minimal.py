"""Minimal example for the TMC5160 — move a stepper with the internal ramp generator.

Constructs the driver with the defaults (SPI Mode 3, StealthChop, 256
microsteps), sets current, speed and acceleration, then moves to positions
and runs in velocity mode. The chip's motion controller does the work: no
STEP pulses are generated by the host.
"""

import time
from machine import SPI, Pin
from periph.connection.spi_micropython import SPIConnection
from periph.connection.output_pin import MicroPythonOutputPin
from periph.chips.motor.tmc5160 import TMC5160Minimal

spi = SPI(1, baudrate=1_000_000, polarity=1, phase=1)    # Create SPI bus, (bus=1, baudrate=1 MHz, mode 3) → SPI
connection = SPIConnection(spi, Pin(5, Pin.OUT))         # Create SPI connection, (spi, cs) → SPIConnection
motor = TMC5160Minimal(connection, en_pin=MicroPythonOutputPin(4))  # Create TMC5160 driver, (connection, bus_type='spi', r_sense_ohm=0.075 Ω, en_pin, address=0, echo=True, multi_node=False, fclk_hz=12000000 Hz)

motor.set_current(1.5)                                   # Set run current, (rms_a A RMS) → None
motor.set_speed(300)                                     # Set target speed, (full_steps_per_s full steps/s) → None
motor.set_acceleration(800)                              # Set acceleration, (full_steps_per_s2 full steps/s²) → None
motor.enable()                                           # Power stage on, () → None
motor.move_to(400)                                       # Start a positioning move, (position full steps) → None
motor.wait_until_reached()                               # Wait for the target, (timeout_s=None) → bool
print('position:', motor.position())                     # Read actual position, () → float full steps
motor.move(-400)                                         # Blocking relative move, (full_steps, full_steps_per_s=None) → None
motor.run(200)                                           # Velocity mode, (full_steps_per_s full steps/s) → None
time.sleep(2)
print('velocity:', motor.velocity())                     # Read actual velocity, () → float full steps/s
motor.stop()                                             # Controlled stop, () → None
motor.wait_until_reached()                               # Wait for standstill, (timeout_s=None) → bool
print('standstill:', motor.is_standstill())              # Read standstill flag, () → bool
print('fault:', motor.read_fault())                      # Read fault bitmask, () → int
motor.disable()                                          # Power stage off, () → None
